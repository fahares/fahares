def audit_page_text(p_num, text):
    errors = []
    # Check Persian digits
    if re.search(r'[۰-۹]', text):
        errors.append("Contains Persian digits")
    # Check bold markdown
    if "**" in text:
        errors.append("Contains **")
    # Check bullet referral
    if "● ←" in text or re.search(r'●\s+[^/]+←', text):
        errors.append("Contains bullet referral")
    # Check non-standard referral
    if re.search(r'[\r\n][^\r\n]+>[^\r\n]+[\r\n]', text):
        errors.append("Contains '>' referral instead of '←'")
    # Check بی‌کا and بی‌تا with normal space
    if re.search(r'\bبی کا\b', text):
        errors.append("Contains 'بی کا' without ZWNJ")
    if re.search(r'\bبی تا\b', text):
        errors.append("Contains 'بی تا' without ZWNJ")
    # Check transliteration blank line:
    # A line in Latin chars (e.g. [a-zāīūšžč\'-]+) followed immediately by non-empty line
    lines = text.splitlines()
    for i, line in enumerate(lines):
        line_str = line.strip()
        if line_str and re.match(r'^[a-zA-Zāīūšžčḍṣṭẓḥ' + r"'\- =(),0-9–/.]+$", line_str):
            # Check if next line is not empty and not the end of the text
            if i + 1 < len(lines):
                next_line = lines[i+1].strip()
                if next_line != "":
                    errors.append(f"Line {i+1} transliteration '{line_str}' not followed by blank line (next: '{next_line[:30]}')")
    
    # Check numbered manuscripts blank line:
    for i, line in enumerate(lines):
        line_str = line.strip()
        m = re.match(r'^([1-9][0-9]?)\.\s+', line_str)
        if m:
            num = int(m.group(1))
            if num > 1:
                # Previous line before num must be empty
                if i > 0 and lines[i-1].strip() != "":
                    errors.append(f"Manuscript {num} (line {i+1}) not preceded by blank line")

    return errors


def main():
    print("--- Auditing Batch 2 page texts ---")
    all_ok = True
    for p, text in sorted(PAGES.items()):
        errs = audit_page_text(p, text)
