def main():
    filepath = 'sources/text/fahares_vol_03.txt'
    with open(filepath, 'r', encoding='utf-8') as f:
        text = f.read()

    pages = re.split(r'(<!-- page: \d+ -->)', text)
    # pages[0] is preamble before first page tag
    # pages[1] is <!-- page: 13 -->
    # pages[2] is content of page 13
    # pages[3] is <!-- page: 14 -->
    # pages[4] is content of page 14 ...
    
    total_tags = (len(pages) - 1) // 2
    print(f"Total page tags found: {total_tags}")
    assert total_tags == 1016, f"Expected 1016 tags, got {total_tags}"

    modified_count = 0
    for i in range(1, len(pages), 2):
        m = re.match(r'<!-- page: (\d+) -->', pages[i])
        pnum = int(m.group(1))
        if pnum in PAGES_CONTENT:
            # Replace content (pages[i+1])
            pages[i+1] = PAGES_CONTENT[pnum]
            modified_count += 1

    print(f"Reconstructed {modified_count} pages.")
    assert modified_count == len(PAGES_CONTENT), f"Expected {len(PAGES_CONTENT)} pages modified, got {modified_count}"

    new_text = "".join(pages)
    
    # Check page tag count in new_text
    new_tags = len(re.findall(r'<!-- page: \d+ -->', new_text))
    print(f"Total page tags after reconstruction: {new_tags}")
    assert new_tags == 1016, f"Tag count mismatch! Expected 1016, got {new_tags}"

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(new_text)

    print("Successfully updated fahares_vol_03.txt!")

if __name__ == '__main__':
    main()
