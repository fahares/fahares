ar_digits = '٠١٢٣٤٥٦٧٨٩'
fa_digits = '۰۱۲۳۴۵۶۷۸۹'

def to_en_digits(text):
    res = []
    for c in text:
        if c in ar_digits: res.append(str(ar_digits.index(c)))
        elif c in fa_digits: res.append(str(fa_digits.index(c)))
        else: res.append(c)
    return ''.join(res)

def normalize_line(text):
    text = unicodedata.normalize('NFKC', text)
    text = text.replace('ي', 'ی').replace('ك', 'ک').replace('•', '●').replace('▶', '●')
    text = to_en_digits(text)
    # Fix * to ×
    text = re.sub(r'(\d+(?:/\d+)?)\s*[\*xX×]\s*(\d+(?:/\d+)?)', r'\1×\2', text)
    text = re.sub(r'(\d+)\s*[\*xX×]\s*(\d+)', r'\1×\2', text)
    # Fix brackets
    text = re.sub(r'\]\s*([0-9\-\s/]+)\s*\[', r'[\1]', text)
    text = re.sub(r'\]\s*(رایانه|عکسی|نشریه[^\]]*|الفبائی[^\]]*|ف[^\]]*)\s*\[', r'[\1]', text)
    text = re.sub(r'\[\s*(رایانه|عکسی)\s*\[', r'[\1]', text)
    text = re.sub(r'\]\s*(رایانه|عکسی)\s*\]', r'[\1]', text)
    text = re.sub(r'\[\s*ف\s*[:؛]\s*', '[ف: ', text)
    text = re.sub(r'[:؛]?\s*ف\]\s*سم\s*', ' سم [ف: ', text)
    text = re.sub(r'\]\s*سم\s*', ' سم [', text)
    text = re.sub(r'\[\s*([0-9]+)\s*-\s*([0-9]+)\s*\[', r'[\1-\2]', text)
    text = re.sub(r'\s*([←<])\s*', ' ← ', text)
    text = re.sub(r'[ \t]*([:؛])[ \t]*', r'\1 ', text)
    text = re.sub(r'؛[ \t]*$', '؛', text)
    text = re.sub(r'[ \t]+', ' ', text)
    return text.strip()

