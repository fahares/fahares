def is_pure_latin(l):
    return bool(re.match(r'^[a-zA-Zāīūṭṣḍẓḥṯš\s\-\'\,\.\(\)\=\:\;\d\/]+$', l)) and bool(re.search(r'[a-zA-Zāīūṭṣḍẓḥṯš]', l))

def is_referral(l):
    return '←' in l and not l.startswith('●')

def format_page_lines(lines):
    out = []
    for i, l in enumerate(lines):
        is_heading = l.startswith('●')
        is_sh = bool(re.match(r'^\d+\.\s*', l))
        is_ref = is_referral(l)
        is_ghayr = (l == 'غیر همانند:')
        
        prev_l = out[-1] if out else ''
        prev_is_latin = is_pure_latin(prev_l) if prev_l else False
        prev_is_ref = is_referral(prev_l) if prev_l else False
        prev_is_ghayr = (prev_l == 'غیر همانند:')
        
        needs_blank = False
        if out:
            if is_heading or is_sh or is_ref or is_ghayr or prev_is_latin or prev_is_ref or prev_is_ghayr:
                needs_blank = True
        
        if needs_blank and out and out[-1] != '':
            out.append('')
        
        out.append(l)
        
        if is_pure_latin(l) or is_ref or is_ghayr:
            out.append('')
            
    text = '\n'.join(out)
    text = re.sub(r'\n{3,}', '\n\n', text).strip()
    return text

def cluster(col_spans):
    lines = []
    spans_sorted = sorted(col_spans, key=lambda s: (s[1]+s[3])/2)
    for s in spans_sorted:
        y_mid = (s[1]+s[3])/2
        placed = False
        for line in lines:
            line_y_mid = sum((item[1]+item[3])/2 for item in line) / len(line)
            if abs(y_mid - line_y_mid) < 13:
                line.append(s)
                placed = True
                break
        if not placed:
            lines.append([s])
    lines.sort(key=lambda line: sum((item[1]+item[3])/2 for item in line) / len(line))
    res_lines = []
    for line in lines:
        line_text = ''.join(item[4] for item in line)
        is_latin = bool(re.search(r'[a-zA-Zāīūṭṣḍẓḥṯš]', line_text)) and not bool(re.search(r'[\u0600-\u06FF]', line_text))
        if is_latin:
            line.sort(key=lambda s: s[0])
        else:
            line.sort(key=lambda s: -s[2])
        norm = normalize_line(' '.join(s[4] for s in line))
        if norm:
            res_lines.append(norm)
    return res_lines

