    protected $signature = 'fahares:seed-person-aliases {--reindex-works : Also reindex all authored works to Meilisearch}';
    protected $description = 'Seed curated aliases, titles, and common naming variations for prominent scholars and authors';

    public function handle(): int
    {
        $this->info('Starting to seed curated aliases for scholars...');

        $aliasesMap = $this->getAliasesDefinitions();
        $updatedCount = 0;
        $totalWorksCount = 0;

        foreach ($aliasesMap as $item) {
            $person = null;
            if (!empty($item['id'])) {
                $person = Person::find($item['id']);
            }

            if (!$person && !empty($item['name'])) {
                $person = Person::where('name', $item['name'])->first();
            }

            if (!$person && !empty($item['name_like'])) {
                $person = Person::where('name', 'like', $item['name_like'])->orderByDesc('works_count')->first();
            }

            if (!$person) {
                $this->warn("Person not found: " . ($item['name'] ?? $item['id'] ?? 'unknown'));
                continue;
            }

            // Merge and deduplicate aliases
            $currentAliases = (array) ($person->aliases ?? []);
            $newAliases = array_values(array_unique(array_filter(array_merge($currentAliases, $item['aliases']))));

            $person->aliases = $newAliases;
            $person->save();

            // Re-index person in Scout
            $person->searchable();
            $updatedCount++;

            $this->line("<info>[✓] Updated:</info> {$person->name} (ID: {$person->id}) -> [" . implode('، ', $newAliases) . "]");

            if ($this->option('reindex-works')) {
                $works = Work::where('author_id', $person->id)->with(['subjects:id,name', 'languages:id,name', 'author:id,name,aliases'])->get();
                if ($works->isNotEmpty()) {
                    $works->searchable();
                    $totalWorksCount += $works->count();
                }
            }
        }

        $this->info("Successfully updated {$updatedCount} scholars.");
        if ($this->option('reindex-works')) {
            $this->info("Re-indexed {$totalWorksCount} authored works into Meilisearch.");
        }

        return self::SUCCESS;
    }

