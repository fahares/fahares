    /** «سوره‌ی کهف، آیه‌ی ۴۶» for «18:46», «… آیه‌های ۱ تا ۵» for «2:1-5». */
    public static function label(string $address): ?string
    {
        if (! preg_match('/^(\d+):(\d+)(?:-(\d+))?$/', $address, $m) || ! isset(self::SURAS[(int) $m[1]])) {
            return null;
        }

        return Fa::digits('سوره‌ی ' . self::SURAS[(int) $m[1]] . '، ' . (isset($m[3]) ? "آیه‌های {$m[2]} تا {$m[3]}" : "آیه‌ی {$m[2]}"));
    }
}
